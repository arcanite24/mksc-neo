typedef struct
{
    const uint8_t *bytes;
    size_t size;
    uint32_t section_count;
    uint64_t section_table_offset;
    uint8_t pack_digest[PORTABLE_ASSET_PACK_DIGEST_SIZE];
    uint8_t deterministic_digest[PORTABLE_ASSET_PACK_DIGEST_SIZE];
    const struct PortableAssetSectionView *resolved_sections;
    /* Application selection, never serialized into imported pack bytes.
     * 0 Original; 1 Modern. Composition inherits the lowest-priority base. */
    uint8_t driving_profile;
} PortableAssetPackView;

typedef struct PortableAssetSectionView
{
    uint32_t kind;
    uint32_t content_id;
    uint32_t version;
    uint32_t flags;
    uint32_t semantic_revision;
    const uint8_t *bytes;
    size_t size;
} PortableAssetSectionView;

PortableAssetPackStatus portable_asset_pack_open(
    const uint8_t *bytes, size_t size, PortableAssetPackView *out);
PortableAssetPackStatus portable_asset_pack_find_section(
    const PortableAssetPackView *pack, uint32_t kind, uint32_t content_id,
    PortableAssetSectionView *out);
PortableAssetPackStatus portable_asset_pack_section_at(
    const PortableAssetPackView *pack, uint32_t index,
    PortableAssetSectionView *out);
/* Compose already validated packs in low-to-high priority order. Later sections
 * replace by (kind, content_id); new keys append in their first-seen order.
 * Caller owns storage and all input payloads for the lifetime of out. Storage
 * must not alias an input section table. Storage may change on failure; the
 * output view is assigned only on success.
 * One layer preserves its original fingerprints. An unchanged effective set
 * of deterministic sections preserves the base deterministic fingerprint. */
PortableAssetPackStatus portable_asset_pack_compose(
    const PortableAssetPackView *const *layers, size_t layer_count,
    PortableAssetSectionView *storage, size_t capacity, PortableAssetPackView *out);
const char *portable_asset_pack_status_name(PortableAssetPackStatus status);
/* SHA-256 over the concatenation of count byte ranges (mod fingerprints). */
void portable_asset_pack_sha256(const uint8_t *const *parts,const size_t *sizes,
    size_t count,uint8_t output[PORTABLE_ASSET_PACK_DIGEST_SIZE]);

