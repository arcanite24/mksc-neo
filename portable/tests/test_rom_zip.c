static int failures;

static void expect(int condition, const char *what)
{
    if (!condition)
    {
        fprintf(stderr, "FAIL: %s\n", what);
        ++failures;
    }
}

static void expected_payload(uint8_t *out, size_t capacity, size_t *size)
{
    size_t length = 0u;
    static const char letters[] = "ABCDEFGH";
    for (int i = 0; i < 120; ++i)
    {
        const int written = snprintf((char *)out + length, capacity - length, "lap %d: ", i);
        if (written < 0 || (size_t)written >= capacity - length)
        {
            expect(0, "fixture label fits"); *size = 0u; return;
        }
        length += (size_t)written;
        for (int repeat = 0; repeat < i % 5 + 1; ++repeat)
        {
            const size_t tail = strlen(letters + i % 8);
            if (tail >= capacity - length)
            {
                expect(0, "fixture text fits"); *size = 0u; return;
            }
            memcpy(out + length, letters + i % 8, tail);
            length += tail;
        }
        out[length++] = '\n';
    }
    *size = length;
}

int main(void)
{
    char error[256];
    uint8_t *rom = NULL;
    size_t size = 0u;
    uint8_t expected[4096];
    size_t expected_size = 0u;
    expected_payload(expected, sizeof expected, &expected_size);

    expect(mksc_rom_zip_detect(dynamic_zip, sizeof dynamic_zip), "zip detected");
    expect(!mksc_rom_zip_detect(expected, expected_size), "plain data is not a zip");
    expect(mksc_rom_zip_extract(dynamic_zip, sizeof dynamic_zip, ".gba", 1u << 20, &rom, &size, error, sizeof error),
           "dynamic entry extracts");
    expect(size == expected_size && rom != NULL && memcmp(rom, expected, size) == 0, "dynamic entry matches");
    free(rom);

    expect(mksc_rom_zip_extract(dynamic_zip, sizeof dynamic_zip, ".nds;.v64;.GBA;.n64", 1u << 20,
                                &rom, &size, error, sizeof error), "extension set selects matching entry");
    expect(size == expected_size && rom && memcmp(rom, expected, size) == 0, "extension set payload matches");
    free(rom);

    expect(mksc_rom_zip_extract(fixed_zip, sizeof fixed_zip, ".nds", 1u << 20, &rom, &size, error, sizeof error),
           "only file extracts");
    expect(size == 17u && rom != NULL && memcmp(rom, "hello hello hello", 17u) == 0, "fixed entry matches");
    free(rom);

    expect(!mksc_rom_zip_extract(dynamic_zip, sizeof dynamic_zip, ".gba", 100u, &rom, &size, error, sizeof error),
           "oversized entry rejected");
    expect(!mksc_rom_zip_extract(dynamic_zip, sizeof dynamic_zip, ".nds", 1u << 20, &rom, &size, error, sizeof error) &&
               strstr(error, ".nds") != NULL,
           "archive without the wanted extension names it");
    uint8_t damaged[sizeof dynamic_zip];
    memcpy(damaged, dynamic_zip, sizeof damaged);
    damaged[200] ^= 0x5au;
    expect(!mksc_rom_zip_extract(damaged, sizeof damaged, ".gba", 1u << 20, &rom, &size, error, sizeof error),
           "damaged data rejected");
    expect(!mksc_rom_zip_extract(damaged, 40u, ".gba", 1u << 20, &rom, &size, error, sizeof error), "truncated rejected");
    if (failures == 0) puts("rom zip: PASS");
    return failures != 0;
}
