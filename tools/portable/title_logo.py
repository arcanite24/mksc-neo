"""Shrink the project logo PNG into a raw-deflate ARGB header for the title screen.

Only the standard library is used, so every build host can run it. The image
is cropped to its visible pixels and box-filtered with alpha weighting, so the
transparent margin never bleeds dark fringes into the outline.
"""
import argparse
from pathlib import Path
import struct
import zlib


def decode_png(data):
    if data[:8] != b'\x89PNG\r\n\x1a\n':
        raise ValueError('not a PNG')
    offset, idat, header = 8, [], None
    while offset < len(data):
        length, kind = struct.unpack('>I4s', data[offset:offset + 8])
        body = data[offset + 8:offset + 8 + length]
        offset += 12 + length
        if kind == b'IHDR':
            header = struct.unpack('>IIBBBBB', body)
        elif kind == b'IDAT':
            idat.append(body)
        elif kind == b'IEND':
            break
    if header is None:
        raise ValueError('missing IHDR')
    width, height, depth, color, _, _, interlace = header
    if depth != 8 or color not in (2, 6) or interlace:
        raise ValueError('expected 8-bit non-interlaced RGB or RGBA')
    channels = 4 if color == 6 else 3
    raw = zlib.decompress(b''.join(idat))
    stride = width * channels
    rows, previous = [], bytearray(stride)
    for y in range(height):
        start = y * (stride + 1)
        kind, line = raw[start], bytearray(raw[start + 1:start + 1 + stride])
        for i in range(stride):
            left = line[i - channels] if i >= channels else 0
            up = previous[i]
            corner = previous[i - channels] if i >= channels else 0
            if kind == 1:
                line[i] = (line[i] + left) & 255
            elif kind == 2:
                line[i] = (line[i] + up) & 255
            elif kind == 3:
                line[i] = (line[i] + (left + up) // 2) & 255
            elif kind == 4:
                guess = left + up - corner
                pa, pb, pc = abs(guess - left), abs(guess - up), abs(guess - corner)
                line[i] = (line[i] + (left if pa <= pb and pa <= pc else up if pb <= pc else corner)) & 255
            elif kind != 0:
                raise ValueError(f'row {y}: unknown filter {kind}')
        rows.append(line)
        previous = line
    if channels == 3:
        rows = [bytearray(b for i in range(0, stride, 3) for b in (*row[i:i + 3], 255)) for row in rows]
    return width, height, rows


def crop(width, height, rows):
    visible = [(x, y) for y in range(height) for x in range(width) if rows[y][x * 4 + 3] > 8]
    if not visible:
        raise ValueError('image is fully transparent')
    left, right = min(x for x, _ in visible), max(x for x, _ in visible) + 1
    top, bottom = min(y for _, y in visible), max(y for _, y in visible) + 1
    return right - left, bottom - top, [row[left * 4:right * 4] for row in rows[top:bottom]]


def shrink(width, height, rows, target):
    if width <= target:
        return width, height, rows
    out_height = max(1, round(height * target / width))
    out = []
    for oy in range(out_height):
        y0, y1 = oy * height // out_height, max(oy * height // out_height + 1, (oy + 1) * height // out_height)
        line = bytearray()
        for ox in range(target):
            x0, x1 = ox * width // target, max(ox * width // target + 1, (ox + 1) * width // target)
            r = g = b = a = 0
            for y in range(y0, y1):
                row = rows[y]
                for x in range(x0, x1):
                    alpha = row[x * 4 + 3]
                    r += row[x * 4] * alpha
                    g += row[x * 4 + 1] * alpha
                    b += row[x * 4 + 2] * alpha
                    a += alpha
            count = (y1 - y0) * (x1 - x0)
            line += bytes((r // a, g // a, b // a, (a + count // 2) // count) if a else (0, 0, 0, 0))
        out.append(line)
    return target, out_height, out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('png', type=Path)
    parser.add_argument('--width', type=int, default=1024)
    parser.add_argument('--header', type=Path, required=True)
    args = parser.parse_args()
    width, height, rows = shrink(*crop(*decode_png(args.png.read_bytes())), args.width)
    argb = bytearray()
    for row in rows:
        for x in range(width):
            r, g, b, a = row[x * 4:x * 4 + 4]
            argb += struct.pack('<I', a << 24 | r << 16 | g << 8 | b)
    packer = zlib.compressobj(9, zlib.DEFLATED, -15)
    packed = packer.compress(bytes(argb)) + packer.flush()
    lines = [', '.join(f'0x{b:02x}' for b in packed[i:i + 24]) for i in range(0, len(packed), 24)]
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text(
        '/* Generated by tools/portable/title_logo.py; do not edit. */\n'
        f'enum {{ TITLE_LOGO_WIDTH = {width}, TITLE_LOGO_HEIGHT = {height} }};\n'
        '/* Raw deflate of little-endian straight-alpha ARGB pixels. */\n'
        'static const unsigned char title_logo_deflate[] = {\n' + ',\n'.join(lines) + '};\n')


if __name__ == '__main__':
    main()
